import { readFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { describe, expect, it } from "vitest"
import { THEME_COLORS } from "@/lib/theme"

const read = (path: string) =>
  readFileSync(fileURLToPath(new URL(path, import.meta.url)), "utf8").replace(
    /\/\*[\s\S]*?\*\//g,
    ""
  )

const generated = read("./brand/brand.generated.css")
const theme = read("./brand/theme.css")
const tokens = read("../theme/tokens.css")

/** Custom properties declared in the rule whose selector matches. */
function block(css: string, selector: RegExp) {
  const rule = new RegExp(`${selector.source}\\s*\\{([^}]*)\\}`).exec(css)
  if (!rule) throw new Error(`no rule for ${selector}`)
  return new Map(
    [...rule[1].matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)].map(([, n, v]) => [
      n,
      v.trim(),
    ])
  )
}

const cdLight = block(generated, /:root/)
const cdDark = block(generated, /\.dark/)
const mapped = new Map([
  ...block(theme, /:root(?=\s*\{)/),
  ...block(theme, /:root,\s*\[data-mode\]/),
])

describe("the Cofferdam brand layer", () => {
  it("uses the generated sheet as cofferdam-branding wrote it", () => {
    expect(
      readFileSync(
        fileURLToPath(new URL("./brand/brand.generated.css", import.meta.url)),
        "utf8"
      )
    ).toMatch(/^\/\* AUTO-GENERATED by cofferdam-branding/)
  })

  it("maps only brand tokens the app has, to tokens the brand declares", () => {
    const appTokens = new Set(
      [...tokens.matchAll(/(--brand-[\w-]+)\s*:/g)].map(([, n]) => n)
    )
    const brandTokens = new Set([...cdLight.keys(), ...cdDark.keys()])
    for (const [name, value] of mapped) {
      expect(appTokens.has(name), name).toBe(true)
      for (const [, ref] of value.matchAll(/var\((--[\w-]+)\)/g)) {
        expect(
          brandTokens.has(ref) || appTokens.has(ref) || mapped.has(ref),
          `${name} reads ${ref}`
        ).toBe(true)
      }
    }
  })

  it("keeps the primary action ink, never the accent", () => {
    expect(mapped.get("--brand-accent")).toBe("var(--cd-fg)")
    expect(mapped.get("--brand-focus")).toBe("var(--brand)")
  })

  it("sets Geist and Geist Mono", () => {
    expect(mapped.get("--brand-font-sans")).toBe("var(--cd-font-sans)")
    expect(cdLight.get("--cd-font-sans")).toMatch(/^"Geist"/)
    expect(cdLight.get("--cd-font-mono")).toMatch(/^"Geist Mono"/)
    expect(theme).toContain('url("./fonts/Geist-Variable-latin.woff2")')
  })

  it("paints the browser chrome in the brand's web background", () => {
    expect(mapped.get("--brand-surface")).toBe("var(--cd-web-bg)")
    expect(cdLight.get("--cd-web-bg")).toBe(THEME_COLORS.light)
    expect(cdDark.get("--cd-web-bg")).toBe(THEME_COLORS.dark)
  })
})
